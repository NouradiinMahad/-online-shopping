let currentLang = localStorage.getItem('site_lang') || 'en';

function applyTranslations(lang) {
    currentLang = lang;
    localStorage.setItem('site_lang', lang);
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            if (el.tagName === 'INPUT' && el.type !== 'button' && el.type !== 'submit') {
                el.placeholder = translations[lang][key];
            } else {
                // If it contains a child (like the cart badge), we must preserve it
                if(el.id === 'cart-toggle') {
                    const badge = el.querySelector('.badge');
                    el.textContent = translations[lang][key];
                    if(badge) el.appendChild(badge);
                } else if(el.tagName === 'LABEL') {
                   // Normal replacement
                   el.textContent = translations[lang][key];
                } else {
                    el.textContent = translations[lang][key];
                }
            }
        }
    });

    const isLoginModeText = document.getElementById('submit-auth');
    if(isLoginModeText) {
        if(isLoginModeText.textContent === "Login" || isLoginModeText.textContent === "Soo Gal" || isLoginModeText.textContent === "دخول") {
             // Keep state equivalent
             document.getElementById('submit-auth').textContent = translations[lang]['login_btn'];
        } else {
             document.getElementById('submit-auth').textContent = translations[lang]['sign_up'];
        }
    }
    
    // Switch RTL
    document.dir = lang === 'ar' ? 'rtl' : 'ltr';
    if(lang === 'ar') {
        document.body.classList.add('rtl-mode');
    } else {
        document.body.classList.remove('rtl-mode');
    }
}

// On page load
document.addEventListener('DOMContentLoaded', () => {
    applyTranslations(currentLang);
    const switchers = document.querySelectorAll('.lang-switcher');
    switchers.forEach(s => {
        s.value = currentLang;
        s.addEventListener('change', (e) => {
            applyTranslations(e.target.value);
            // Re-render products to apply layout direction changes if necessary
            if(typeof renderProducts === "function") {
               renderProducts();
            }
        });
    });

    // Theme Logic
    const savedTheme = localStorage.getItem('site_theme') || 'dark';
    if(savedTheme === 'light') {
        document.body.classList.add('light-mode');
    }
    
    document.querySelectorAll('.theme-toggle').forEach(btn => {
        btn.textContent = savedTheme === 'light' ? '🌙' : '☀️';
        btn.addEventListener('click', () => {
            const isLight = document.body.classList.toggle('light-mode');
            const newTheme = isLight ? 'light' : 'dark';
            localStorage.setItem('site_theme', newTheme);
            document.querySelectorAll('.theme-toggle').forEach(b => {
                b.textContent = isLight ? '🌙' : '☀️';
            });
        });
    });
});
